U.check(len(pc) == len(S["customers"]) and (pc.orders == 0).any(), "every assigned customer, zeros kept")

# %% [markdown]
# ## 4 · Two effects, with intervals (6')
#
# ✏️ **Exercise** · Write `diff_ci(df, metric)`: the difference in means treatment minus control, its 95% interval
# (normal approximation, unequal variances) and the relative difference. Return a dict with `diff`, `lo`, `hi`,
# `rel`, `se`.

# %%
def diff_ci(df: pd.DataFrame, metric: str = "orders") -> dict:
    # BEGIN SOLUTION
    t = df.loc[df.variant == "treatment", metric]
    c = df.loc[df.variant == "control", metric]
    d = t.mean() - c.mean()
    se = np.sqrt(t.var(ddof=1) / len(t) + c.var(ddof=1) / len(c))
    return {"diff": d, "se": se, "lo": d - 1.96 * se, "hi": d + 1.96 * se, "rel": d / c.mean()}
    # END SOLUTION


# %%
try:
    overall, triggered = diff_ci(pc), diff_ci(pc[pc.triggered])
except NotImplementedError:
    overall, triggered = U.reference("d1_1_overall"), U.reference("d1_1_triggered")
U.keep("d1_1_overall", overall)
U.keep("d1_1_triggered", triggered)
show = pd.DataFrame({"all assigned (diluted)": overall, "triggered": triggered}).T
print(show[["diff", "lo", "hi", "rel"]].round(4))
dilution = triggered["diff"] * rate
print(f"triggered difference x trigger rate = {dilution:.4f}   (overall difference {overall['diff']:.4f})")
U.check(abs(dilution - overall["diff"]) < 2 * overall["se"], "the overall effect is the triggered effect, diluted")
U.check(triggered["diff"] / triggered["se"] > overall["diff"] / overall["se"],
        "the triggered estimate stands more standard errors away from zero")

# %% [markdown]
# 🔍 **Look at** the two `rel` values. The diluted relative lift is smaller because more than half of the customers
# could not be affected at all, and their noise is still in the average. A decision about the ranking concerns
# the people who search; report the triggered effect, and give the diluted one for the whole-business view.

# %% [markdown]
# ## 5 · Is exposure balanced? (3')
#
# Triggering is valid only if the treatment cannot change who triggers. Here the trigger (a search) happens
# before the ranking is shown, so the trigger rate must be equal in both arms.
#
# ✏️ **Exercise** · Compute `balance_p`: the p-value of a chi-square test of triggered against variant.

# %%
def trigger_balance(df: pd.DataFrame) -> float:
    # BEGIN SOLUTION
    table = pd.crosstab(df.variant, df.triggered)
    return float(stats.chi2_contingency(table)[1])
    # END SOLUTION


# %%
try:
    balance_p = trigger_balance(pc)
except NotImplementedError:
    balance_p = U.reference("d1_1_balance_p")
U.keep("d1_1_balance_p", balance_p)
print(pd.crosstab(pc.variant, pc.triggered, normalize="index").round(4), "\np =", round(balance_p, 3))
U.check(balance_p > 0.001, "trigger rates do not differ between the arms")

