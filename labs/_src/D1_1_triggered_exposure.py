# %% [markdown]
# ## 2 · Who was exposed, and when (6')
#
# Assignment happens on day 0 for everyone. **Exposure** happens at a customer's first search in the test
# period (day 0 or later): that is when the ranking could first make a difference. The **trigger condition** is
# "searched at least once"; it is logged in both arms, so control customers who *would* have seen the new
# ranking are flagged too (counterfactual logging).
#
# ✏️ **Exercise** · Write `exposure_sql()`: one row per assigned customer with `customer_id`, `variant`, and
# `exposed_day` (the first search day, or NULL when the customer never searched). Use a left join.

# %%
def exposure_sql() -> str:
    # BEGIN SOLUTION
    return """
    select a.customer_id, a.variant, f.exposed_day
    from assignments a
    left join (select customer_id, min(day) as exposed_day
               from searches where day >= 0 group by customer_id) f
      on f.customer_id = a.customer_id
    """
    # END SOLUTION


# %%
try:
    q = exposure_sql()
except NotImplementedError:
    q = U.reference("d1_1_exposure_sql")
U.keep("d1_1_exposure_sql", q)
exposure = U.sql(q)
rate = exposure.exposed_day.notna().mean()
print(f"triggered: {rate:.1%} of assigned customers")
print(exposure.groupby("variant").exposed_day.describe()[["count", "mean", "50%"]])
U.check(len(exposure) == len(S["customers"]) and 0.3 < rate < 0.6, "one row per assigned customer; 30 to 60% triggered")

# %% [markdown]
# ## 3 · Orders per customer, in SQL (6')
#
# ✏️ **Exercise** · Write `per_customer_sql()`: one row per assigned customer with `customer_id`, `variant`,
# `triggered` (true or false) and `orders` (orders in the test period, day 0 to 27; zero when none). Customers
# without an order must stay in the table with 0: dropping them is the most common bug in this query.

# %%
def per_customer_sql() -> str:
    # BEGIN SOLUTION
    return """
    with first_search as (
        select customer_id, min(day) as exposed_day from searches where day >= 0 group by customer_id),
    test_orders as (
        select customer_id, count(*) as orders from orders where day >= 0 group by customer_id)
    select a.customer_id, a.variant,
           f.exposed_day is not null as triggered,
           coalesce(o.orders, 0) as orders
    from assignments a
    left join first_search f using (customer_id)
    left join test_orders o using (customer_id)
    """
    # END SOLUTION


# %%
